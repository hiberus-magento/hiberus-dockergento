// aiContext writes the project context an agent reads before it starts: AGENTS.md, a CLAUDE.md
// pointing at it when there is none, and the MCP server in .mcp.json.
//
// Ported from console/commands/ai-context.sh, whose output this is line for line. Only the first
// argument is looked at, as the script's `case "${1:-}"` looked at it; --help in that place never
// reaches here, because bin/run answered it with the command's help before the script ran, and so
// does the router.
func aiContext(args []string, stdout, stderr io.Writer, jsonOutput bool) int {
	if len(args) > 0 && args[0] != "" {
		return failure(stderr, jsonOutput, "ai-context", exitUsage, "invalid_argument",
			fmt.Sprintf("Unknown option: %s", args[0]), binaryName()+" ai-context")
	}

	if _, code := projectOr(stderr, jsonOutput, "ai-context"); code != 0 {
		return code
	}

	result, err := newEngine(stdout, stderr, jsonOutput).WriteAgentContext(here())
	if err != nil {
		var refused core.Refusal
		if asRefusal(err, &refused) {
			return report(stderr, jsonOutput, "ai-context", err)
		}

		// A file that could not be written is not Docker's failure, whatever report would call it
		return failure(stderr, jsonOutput, "ai-context", exitError, "write_failed", err.Error(), "")
	}

	if jsonOutput {
		document, err := json.MarshalIndent(contract.Success("ai-context", result), "", "  ")
		if err != nil {
			fmt.Fprintln(stderr, err)

			return exitError
		}

		fmt.Fprintf(stdout, "%s\n", document)

		return exitOK
	}

	fmt.Fprint(stdout, "\n"+good("Wrote ")+warning(strings.Join(result.Written, " "))+"\n")
	fmt.Fprint(stdout, code(reset)+"  The block in AGENTS.md is regenerated by this command; anything outside it is yours.\n")

	if result.ClaudeNeeds != nil {
		fmt.Fprint(stdout, "\n")
		fmt.Fprint(stderr, warning("CLAUDE.md already exists and was not touched")+"\n")
		fmt.Fprint(stdout, code(reset)+"  Add this line to it so the context is loaded:\n\n    "+
			warning(*result.ClaudeNeeds)+"\n")
	}

	fmt.Fprint(stdout, "\n"+code(reset)+"  Re-run it when the project changes: "+warning(binaryName()+" doctor")+
		code(reset)+" says when it has gone stale.\n\n")

	return exitOK
}
