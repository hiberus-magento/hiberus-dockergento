//
// What setup leaves the proxy for a domain, as the shell's hm_proxy_write_certificate did: a
// mkcert pair for the domain and its wildcard in certs/, and the dynamic file naming them. The
// host programs and Compose share one log, so each test reads a single sequence; mkcert is the
// certificate test's fake, which writes what mkcert would have written.
//

const certifiedDomain = "tienda.local"

// certifyingProxy is a proxy in a directory of the test's own, running or not, over a host with
// the programs given.
func certifyingProxy(t *testing.T, running bool, present ...string) (Proxy, *[]string, *[]string) {
	t.Helper()

	log := &[]string{}
	said := &[]string{}

	host := &programs{log: log, present: map[string]bool{}, installs: map[string]string{}, fails: map[string]bool{}}
	for _, name := range present {
		host.present[name] = true
	}

	containers := []core.Container{}
	if running {
		containers = append(containers, core.Container{ID: "proxy-1", Name: core.ProxyContainer, Running: true})
	}

	return Proxy{
		Engine:       &engine{containers: containers},
		Orchestrator: &orchestrator{log: log},
		Programs:     host,
		Dir:          t.TempDir(),
		Announce:     func(message string) { *said = append(*said, message) },
		Binary:       "hm",
	}, log, said
}

// mkcertCalls is what the log holds for each mkcert run, with its temporary directory hidden.
func mkcertCalls(log []string) []string {
	calls := []string{}

	for _, entry := range log {
		if !strings.HasPrefix(entry, "host mkcert") {
			continue
		}

		fields := strings.Fields(entry)
		for i, field := range fields {
			if filepath.IsAbs(field) {
				fields[i] = filepath.Base(field)
			}
		}

		calls = append(calls, strings.Join(fields, " "))
	}

	return calls
}

func restarts(log []string) []string {
	compose := []string{}

	for _, entry := range log {
		if strings.HasPrefix(entry, "stop") || strings.HasPrefix(entry, "up") {
			compose = append(compose, strings.TrimSpace(entry))
		}
	}

	return compose
}

func read(t *testing.T, path string) string {
	t.Helper()

	contents, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}

	return string(contents)
}

// writePair leaves a real certificate and key in certs/, valid for names until expires.
func writePair(t *testing.T, dir, domain string, expires time.Time, names ...string) {
	t.Helper()

	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}

	template := x509.Certificate{
		SerialNumber: big.NewInt(1),
		Subject:      pkix.Name{CommonName: domain},
		NotBefore:    time.Now().Add(-time.Hour),
		NotAfter:     expires,
		DNSNames:     names,
	}

	der, err := x509.CreateCertificate(rand.Reader, &template, &template, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}

	private, err := x509.MarshalECPrivateKey(key)
	if err != nil {
		t.Fatal(err)
	}

	certs := filepath.Join(dir, "certs")
	if err := os.MkdirAll(certs, 0o755); err != nil {
		t.Fatal(err)
	}

	if err := os.WriteFile(filepath.Join(certs, domain+".pem"),
		pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := os.WriteFile(filepath.Join(certs, domain+"-key.pem"),
		pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: private}), 0o600); err != nil {
		t.Fatal(err)
	}
}

const certifiedDynamic = `# Generated by hm for tienda.local
tls:
  certificates:
    - certFile: /etc/traefik/certs/tienda.local.pem
      keyFile: /etc/traefik/certs/tienda.local-key.pem
`

func TestCertifySignsAWildcardPairAndNamesItForTheProxy(t *testing.T) {
	proxy, log, _ := certifyingProxy(t, false, "mkcert")

	if err := proxy.Certify(certifiedDomain); err != nil {
		t.Fatalf("Certify: %v", err)
	}

	want := []string{"host mkcert -cert-file tienda.local.pem -key-file tienda.local-key.pem tienda.local *.tienda.local"}
	if diff := cmp.Diff(want, mkcertCalls(*log)); diff != "" {
		t.Errorf("mkcert (-want +got):\n%s", diff)
	}

	if got := read(t, filepath.Join(proxy.Dir, "certs", "tienda.local.pem")); got != "CERTIFICATE\n" {
		t.Errorf("certificate = %q", got)
	}

	if got := read(t, filepath.Join(proxy.Dir, "certs", "tienda.local-key.pem")); got != "KEY\n" {
		t.Errorf("key = %q", got)
	}

	if diff := cmp.Diff(certifiedDynamic, read(t, filepath.Join(proxy.Dir, "dynamic", "tienda.local.yml"))); diff != "" {
		t.Errorf("dynamic (-want +got):\n%s", diff)
	}

	// Nothing generated is left behind beside the two directories the proxy mounts
	entries, _ := os.ReadDir(proxy.Dir)
	names := []string{}
	for _, entry := range entries {
		names = append(names, entry.Name())
	}
	if diff := cmp.Diff([]string{"certs", "dynamic"}, names); diff != "" {
		t.Errorf("proxy dir (-want +got):\n%s", diff)
	}

	if got := restarts(*log); len(got) != 0 {
		t.Errorf("a proxy that is not running was touched: %v", got)
	}
}

func TestCertifyWithoutMkcertSkipsAndSaysSo(t *testing.T) {
	proxy, log, said := certifyingProxy(t, true)

	// Says nothing itself and answers with ErrNoMkcert: setup turns it into a note and carries
	// on, and `proxy certify` into a refusal — a success would claim a certificate nobody signed
	if err := proxy.Certify(certifiedDomain); !errors.Is(err, ErrNoMkcert) {
		t.Fatalf("Certify = %v, want ErrNoMkcert", err)
	}

	if got := mkcertCalls(*log); len(got) != 0 {
		t.Errorf("mkcert ran: %v", got)
	}

	for _, file := range []string{"dynamic/tienda.local.yml", "certs/tienda.local.pem"} {
		if _, err := os.Stat(filepath.Join(proxy.Dir, file)); !os.IsNotExist(err) {
			t.Errorf("%s was written without a certificate to name", file)
		}
	}

	if len(*said) != 0 {
		t.Errorf("said %q, want the caller to decide what to say", *said)
	}

	if got := restarts(*log); len(got) != 0 {
		t.Errorf("the proxy was restarted for nothing: %v", got)
	}
}

func TestCertifyRestartsARunningProxySoItServesTheNewPair(t *testing.T) {
	proxy, log, _ := certifyingProxy(t, true, "mkcert")

	if err := proxy.Certify(certifiedDomain); err != nil {
		t.Fatalf("Certify: %v", err)
	}

	if diff := cmp.Diff([]string{"stop", "up"}, restarts(*log)); diff != "" {
		t.Errorf("compose (-want +got):\n%s", diff)
	}
}

func TestCertifyKeepsAValidPairAndLeavesTheProxyAlone(t *testing.T) {
	proxy, log, _ := certifyingProxy(t, true, "mkcert")

	writePair(t, proxy.Dir, certifiedDomain, time.Now().AddDate(1, 0, 0), certifiedDomain, "*."+certifiedDomain)
	if err := os.MkdirAll(filepath.Join(proxy.Dir, "dynamic"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(proxy.Dir, "dynamic", "tienda.local.yml"), []byte(certifiedDynamic), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := proxy.Certify(certifiedDomain); err != nil {
		t.Fatalf("Certify: %v", err)
	}

	if got := mkcertCalls(*log); len(got) != 0 {
		t.Errorf("a valid pair was signed again: %v", got)
	}

	if got := restarts(*log); len(got) != 0 {
		t.Errorf("the proxy was restarted for nothing: %v", got)
	}
}

func TestCertifyWritesTheDynamicFileForAValidPairThatHadNone(t *testing.T) {
	proxy, log, _ := certifyingProxy(t, true, "mkcert")

	writePair(t, proxy.Dir, certifiedDomain, time.Now().AddDate(1, 0, 0), certifiedDomain, "*."+certifiedDomain)

	if err := proxy.Certify(certifiedDomain); err != nil {
		t.Fatalf("Certify: %v", err)
	}

	if got := mkcertCalls(*log); len(got) != 0 {
		t.Errorf("a valid pair was signed again: %v", got)
	}

	if diff := cmp.Diff(certifiedDynamic, read(t, filepath.Join(proxy.Dir, "dynamic", "tienda.local.yml"))); diff != "" {
		t.Errorf("dynamic (-want +got):\n%s", diff)
	}

	if diff := cmp.Diff([]string{"stop", "up"}, restarts(*log)); diff != "" {
		t.Errorf("compose (-want +got):\n%s", diff)
	}
}

func TestCertifySignsAgainAPairThatDoesNotServeTheSubdomainsOrIsExpiring(t *testing.T) {
	cases := map[string]struct {
		expires time.Time
		names   []string
	}{
		"no wildcard": {time.Now().AddDate(1, 0, 0), []string{certifiedDomain}},
		"expiring":    {time.Now().Add(24 * time.Hour), []string{certifiedDomain, "*." + certifiedDomain}},
	}

	for name, pair := range cases {
		t.Run(name, func(t *testing.T) {
			proxy, log, _ := certifyingProxy(t, false, "mkcert")
			writePair(t, proxy.Dir, certifiedDomain, pair.expires, pair.names...)

			if err := proxy.Certify(certifiedDomain); err != nil {
				t.Fatalf("Certify: %v", err)
			}

			if got := mkcertCalls(*log); len(got) != 1 {
				t.Errorf("want mkcert run once, got %v", got)
			}

			if got := read(t, filepath.Join(proxy.Dir, "certs", "tienda.local.pem")); got != "CERTIFICATE\n" {
				t.Errorf("the old certificate was kept: %q", got)
			}
		})
	}
}

func TestCertifyWhenMkcertFailsWritesNothingAndLeavesTheProxyAlone(t *testing.T) {
	proxy, log, _ := certifyingProxy(t, true, "mkcert")
	proxy.Programs.(*programs).fails["mkcert"] = true

	if err := proxy.Certify(certifiedDomain); err == nil {
		t.Fatal("want the failure reported to the caller")
	}

	for _, file := range []string{"dynamic/tienda.local.yml", "certs/tienda.local.pem"} {
		if _, err := os.Stat(filepath.Join(proxy.Dir, file)); !os.IsNotExist(err) {
			t.Errorf("%s was written although mkcert failed", file)
		}
	}

	if got := restarts(*log); len(got) != 0 {
		t.Errorf("the proxy was restarted for nothing: %v", got)
	}
}
