//
// The generated block of AGENTS.md, and the two files around it.
//
// It is a block and not a file because AGENTS.md belongs to the project: people write things in
// it that no generator could know — this branch is a migration, that module is somebody else's,
// do not touch the theme. Regenerating replaces what is between the markers and nothing else.
//
// Ported from console/tasks/agent_context.sh. The bytes are that file's, down to the blank line
// jq leaves after the table, because a context regenerated by the binary must not show up as a
// change in the project's history when nothing about the project changed.
//

// The markers the generated block of AGENTS.md is written between.
const (
	AgentContextBegin = "<!-- hm:begin - generated by hm ai-context, do not edit inside -->"
	AgentContextEnd   = "<!-- hm:end -->"
)

// AgentContext is everything the block is made from.
type AgentContext struct {
	// Binary is the name the tool was invoked as: every command in the block is one the agent is
	// meant to be able to paste.
	Binary string

	// Version is what the block says generated it, "unknown" when nothing says.
	Version string

	// Description is the resolved project: the versions, the URLs, the admin's real front name and
	// whether the data was anonymised.
	Description Description

	// Exclusions are the paths an agent is told not to read, with why.
	Exclusions []AgentExclusion
}

// AgentExclusion is one entry of data/ai-exclusions.json.
type AgentExclusion struct {
	Path   string `json:"path"`
	Reason string `json:"reason"`
}

// AgentContextResult is what writing the context did, in the shape `ai-context --json` answers.
type AgentContextResult struct {
	// Written names the files written, in the order they were.
	Written []string `json:"written"`

	// Root is the directory they were written into.
	Root string `json:"root"`

	// ClaudeNeeds is the line an existing CLAUDE.md lacks to load the context, null when it has it
	// or was created with it: somebody else's CLAUDE.md is never edited.
	ClaudeNeeds *string `json:"claude_needs"`
}

// ReadAgentExclusions reads data/ai-exclusions.json.
func ReadAgentExclusions(contents []byte) ([]AgentExclusion, error) {
	var file struct {
		Exclusions []AgentExclusion `json:"exclusions"`
	}

	if err := json.Unmarshal(contents, &file); err != nil {
		return nil, fmt.Errorf("reading ai-exclusions.json: %w", err)
	}

	return file.Exclusions, nil
}

// AgentContextFingerprint is what a context block was generated from.
//
// A context that says PHP 7.4 in a project that moved to 8.2 is worse than no context at all,
// because an agent obeys it. The hash is of the facts, not of the text, so generating it again on
// an unchanged project produces the same value and `hm doctor` can compare.
//
// The document hashed is the one `jq -S -c` printed for the shell implementation — sorted keys,
// no spaces, jq's escaping, and the newline jq ends its output with — because the values already
// sitting in people's AGENTS.md were computed from it.
func AgentContextFingerprint(domain, magento, admin, anonymised string, services []Service) string {
	var document strings.Builder

	document.WriteString(`{"admin":` + jqString(admin))
	document.WriteString(`,"anonymised":` + jqString(anonymised))
	document.WriteString(`,"domain":` + jqString(domain))
	document.WriteString(`,"magento":` + jqString(magento))
	document.WriteString(`,"services":[`)

	for at, service := range services {
		if at > 0 {
			document.WriteString(",")
		}

		document.WriteString(`{"image":` + jqString(service.Image) + `,"name":` + jqString(service.Name) + `}`)
	}

	document.WriteString("]}\n")

	sum := md5.Sum([]byte(document.String())) //nolint:gosec // see the import

	return hex.EncodeToString(sum[:])
}

// Fingerprint is the block's, from the description it is generated from.
func (c AgentContext) Fingerprint() string {
	services := make([]Service, 0, len(c.Description.Services))
	for _, service := range c.Description.Services {
		services = append(services, Service{Name: service.Name, Image: service.Image})
	}

	anonymised := c.Description.Data.Anonymised
	if anonymised == "" {
		anonymised = "unknown"
	}

	return AgentContextFingerprint(c.Description.Project.Domain, c.Description.Magento.Version,
		c.Description.Project.URLs.Admin, anonymised, services)
}

// Block is the generated block, from the opening marker to the closing one, with no newline
// after it: the shell implementation held it in a variable, and the command substitution that
// filled it took the last newline away.
//
// Every fact comes from the resolved configuration, and none of them is a secret: the database is
// named, its password is not — an agent that needs to connect runs `hm mysql`, which knows the
// credentials without printing them.
func (c AgentContext) Block() string {
	binary := c.Binary
	if binary == "" {
		binary = "hm"
	}

	version := c.Version
	if version == "" {
		version = "unknown"
	}

	d := c.Description

	var b strings.Builder

	line := func(format string, values ...any) { fmt.Fprintf(&b, format, values...) }

	line("%s\n", AgentContextBegin)
	line("<!-- hm:version %s hm:fingerprint %s -->\n\n", version, c.Fingerprint())

	line("## This project runs in Docker, through `%s`\n\n", binary)
	line("Do not work out the versions, the URLs or the container names from `docker-compose.yml`,\n")
	line("`app/etc/env.php` or `composer.lock`. Ask:\n\n")
	line("```bash\n%s describe --json    # versions, services, URLs, state, admin path\n", binary)
	line("%s doctor --json      # what is wrong, with a hint each\n", binary)
	line("%s list --json        # every environment on this machine\n```\n\n", binary)

	line("As it stands now:\n\n")
	line("| | |\n|---|---|\n")
	line("| Project | `%s` |\n", d.Project.Name)
	line("| Magento | %s |\n", orUnknown(d.Magento.Version))
	line("| Mode | %s |\n", orUnknown(d.Magento.Mode))
	line("| State | %s |\n", d.Project.Status)

	if d.Project.URLs.Base != "" {
		line("| Storefront | %s |\n", d.Project.URLs.Base)
	}

	if d.Project.URLs.Admin != "" {
		line("| Admin | %s |\n", d.Project.URLs.Admin)
	}

	names := make([]string, 0, len(d.Services))
	for _, service := range d.Services {
		names = append(names, service.Name)
	}

	line("| Services | %s |\n", strings.Join(names, ", "))

	// Two blank lines and not one: jq -r ended the table with a newline of its own, and the
	// printf after it added the one that was meant
	line("\n\n")

	line("## Running things\n\n```bash\n")
	line("%s magento cache:flush     # the Magento CLI\n", binary)
	line("%s composer install        # Composer, with the vendor sync macOS needs\n", binary)
	line("%s exec php -v             # any command, in the php container\n", binary)
	line("%s logs -n 200 phpfpm      # a service log\n", binary)
	line("%s mysql -q \"SELECT 1\"     # one query\n```\n\n", binary)
	line("`%s bash` opens an interactive shell and takes no command — it understands only `-r`.\n", binary)
	line("Use `%s exec`. Services are named `phpfpm`, `nginx`, `db`, `search`, `redis`; there is no\n", binary)
	line("`mysql` service and no `elasticsearch` service.\n\n")

	line("## What the commands answer with\n\n")
	line("JSON when stdout is not a terminal, as `{\"ok\": true, \"schema_version\": 1, \"data\": {…}}`.\n")
	line("Errors go to stderr with a `message` and a `hint`. The exit code says what happened:\n\n")
	line("| Code | Means |\n|---|---|\n")
	line("| 0 | Fine |\n| 2 | Called wrong |\n| 3 | Docker is not running |\n")
	line("| 4 | Not a project |\n| 5 | A service is not running |\n")
	line("| 6 | **Refused on purpose** — read the message before retrying |\n\n")

	// An agent obeys what it reads, and here that is the mechanism rather than the risk
	line("## The data in this database\n\n")

	if d.Data.Anonymised == "yes" {
		at := d.Data.AnonymisedAt
		if at == "" {
			at = "an earlier date"
		}

		line("Anonymised on %s. It is safe to quote rows in your output.\n\n", at)
	} else {
		line("**This database has not been anonymised.** Treat every row as real personal data:\n")
		line("do not quote customer names, emails, addresses, phone numbers or order contents in\n")
		line("your output. `%s masquerade` anonymises it.\n\n", binary)
	}

	line("## Do not read these\n\n")

	for _, exclusion := range c.Exclusions {
		line("- `%s` — %s\n", exclusion.Path, exclusion.Reason)
	}

	line("\n")

	line("## Do not run these without being asked\n\n")
	line("`%s down -v`, `%s db restore`, `%s db clear`, `%s clean --force`, `%s purge`,\n",
		binary, binary, binary, binary, binary)
	line("`%s masquerade`, `%s docker-stop-all`. Each of them removes something that was not\n", binary, binary)
	line("yours to remove. `%s permissions` prints the full classification.\n\n", binary)

	line("%s", AgentContextEnd)

	return b.String()
}

func orUnknown(value string) string {
	if value == "" {
		return "unknown"
	}

	return value
}

// Placement is how the block gets into AGENTS.md.
type Placement int

const (
	// PlacementCreate writes a new file: there was none.
	PlacementCreate Placement = iota

	// PlacementAppend adds the block at the end of a file that has none.
	PlacementAppend

	// PlacementReplace rewrites the file with the block in place of the old one.
	PlacementReplace
)

// ErrAgentContextNotClosed is a block that was opened and never closed: somebody edited it by
// hand, and rewriting from the opening marker to the end of the file would take their text with
// it.
var ErrAgentContextNotClosed = errors.New("the generated block of AGENTS.md has no closing marker")

// PlaceAgentContext decides how the block goes into AGENTS.md, given what the file holds now.
//
// The file is created when there is none, the block appended when it has none, and replaced in
// place otherwise. Everything outside the markers is left exactly as it was, byte for byte. What
// comes back is what to write — the whole file, or for an append only what is added.
//
// The markers are found the way grep found them: on the first line containing each, wherever it
// is, so a closing marker above the opening one is a block that was never closed.
func PlaceAgentContext(existing []byte, present bool, block string) (Placement, []byte, error) {
	if !present {
		return PlacementCreate, []byte("# Agent notes\n\n" + block + "\n"), nil
	}

	if !bytes.Contains(existing, []byte(AgentContextBegin)) {
		return PlacementAppend, []byte("\n" + block + "\n"), nil
	}

	lines := splitLines(existing)
	begin, end := 0, 0

	for at, line := range lines {
		if begin == 0 && bytes.Contains(line, []byte(AgentContextBegin)) {
			begin = at + 1
		}

		if end == 0 && bytes.Contains(line, []byte(AgentContextEnd)) {
			end = at + 1
		}
	}

	if end == 0 || end <= begin {
		return PlacementReplace, nil, ErrAgentContextNotClosed
	}

	var replaced bytes.Buffer

	for _, line := range lines[:begin-1] {
		replaced.Write(line)
	}

	replaced.WriteString(block + "\n")

	for _, line := range lines[end:] {
		replaced.Write(line)
	}

	return PlacementReplace, replaced.Bytes(), nil
}

// splitLines cuts contents into lines that keep their newline, the last one without it when the
// file does not end with one — which is what head and tail count.
func splitLines(contents []byte) [][]byte {
	lines := [][]byte{}

	for len(contents) > 0 {
		at := bytes.IndexByte(contents, '\n')
		if at < 0 {
			lines = append(lines, contents)

			break
		}

		lines = append(lines, contents[:at+1])
		contents = contents[at+1:]
	}

	return lines
}

// MergeAgentMCP adds this tool's server to a .mcp.json, keeping whatever else is in it.
//
// The file may have other servers, so it is merged rather than written over: the keys keep their
// order, and an entry of this tool's own is replaced where it stands. It reproduces what jq did
// for the shell implementation, its edges included — a file that cannot be parsed is treated as
// empty and replaced, a file with no JSON value in it stays empty — except one: where jq gave up
// (a document that is not an object, or servers that are not one) it left the file untouched
// and a temporary file beside it. Here the file is left untouched and nothing is left beside it;
// write is false.
func MergeAgentMCP(existing []byte, present bool, name, command, directory string) (contents []byte, write bool) {
	documents := []*jsonValue{{kind: jsonObject}}

	if present {
		parsed, err := parseJSONValues(existing)
		if err == nil {
			documents = parsed
		}
	}

	entry := &jsonValue{kind: jsonObject}
	entry.set("command", &jsonValue{kind: jsonString, text: command})
	entry.set("args", &jsonValue{kind: jsonArray, items: []*jsonValue{{kind: jsonString, text: "mcp"}}})
	entry.set("cwd", &jsonValue{kind: jsonString, text: directory})

	var out bytes.Buffer

	for _, document := range documents {
		switch document.kind {
		case jsonNull:
			document = &jsonValue{kind: jsonObject}
		case jsonObject:
		default:
			return nil, false
		}

		servers := document.get("mcpServers")

		switch {
		case servers == nil, servers.kind == jsonNull, servers.kind == jsonFalse:
			servers = &jsonValue{kind: jsonObject}
		case servers.kind != jsonObject:
			return nil, false
		}

		servers.set(name, entry)
		document.set("mcpServers", servers)

		document.pretty(&out, 0)
		out.WriteString("\n")
	}

	return out.Bytes(), true
}

//
// Just enough JSON to do what jq did: values that remember the order their keys came in and the
// literal their numbers were written as, printed the way jq prints them.
//

type jsonKind int

const (
	jsonNull jsonKind = iota
	jsonFalse
	jsonTrue
	jsonNumber
	jsonString
	jsonArray
	jsonObject
)

type jsonValue struct {
	kind   jsonKind
	text   string // a string's contents, or a number's literal
	items  []*jsonValue
	keys   []string
	values map[string]*jsonValue
}

func (v *jsonValue) get(key string) *jsonValue { return v.values[key] }

// set replaces a key where it stands, or adds it at the end, as jq's assignment and object
// addition do.
func (v *jsonValue) set(key string, value *jsonValue) {
	if v.values == nil {
		v.values = map[string]*jsonValue{}
	}

	if _, ok := v.values[key]; !ok {
		v.keys = append(v.keys, key)
	}

	v.values[key] = value
}

// parseJSONValues reads every JSON value in contents, one after another as jq reads its input.
func parseJSONValues(contents []byte) ([]*jsonValue, error) {
	decoder := json.NewDecoder(bytes.NewReader(contents))
	decoder.UseNumber()

	values := []*jsonValue{}

	for {
		// Running out between values is the end of the input; running out inside one is not
		token, err := decoder.Token()
		if errors.Is(err, io.EOF) {
			return values, nil
		}

		if err != nil {
			return nil, err
		}

		value, err := valueFrom(decoder, token)
		if errors.Is(err, io.EOF) {
			return nil, io.ErrUnexpectedEOF
		}

		if err != nil {
			return nil, err
		}

		values = append(values, value)
	}
}

func parseJSONValue(decoder *json.Decoder) (*jsonValue, error) {
	token, err := decoder.Token()
	if err != nil {
		return nil, err
	}

	return valueFrom(decoder, token)
}

func valueFrom(decoder *json.Decoder, token json.Token) (*jsonValue, error) {
	switch typed := token.(type) {
	case nil:
		return &jsonValue{kind: jsonNull}, nil
	case bool:
		if typed {
			return &jsonValue{kind: jsonTrue}, nil
		}

		return &jsonValue{kind: jsonFalse}, nil
	case json.Number:
		return &jsonValue{kind: jsonNumber, text: typed.String()}, nil
	case string:
		return &jsonValue{kind: jsonString, text: typed}, nil
	case json.Delim:
		if typed == '[' {
			array := &jsonValue{kind: jsonArray}

			for decoder.More() {
				item, err := parseJSONValue(decoder)
				if err != nil {
					return nil, err
				}

				array.items = append(array.items, item)
			}

			_, err := decoder.Token()

			return array, err
		}

		object := &jsonValue{kind: jsonObject}

		for decoder.More() {
			key, err := decoder.Token()
			if err != nil {
				return nil, err
			}

			value, err := parseJSONValue(decoder)
			if err != nil {
				return nil, err
			}

			object.set(key.(string), value) //nolint:forcetypeassert // the decoder only hands keys as strings
		}

		_, err := decoder.Token()

		return object, err
	}

	return nil, fmt.Errorf("unexpected JSON token %v", token)
}

// pretty prints the value the way `jq .` does: two spaces, one member per line, and empty
// containers on one line.
func (v *jsonValue) pretty(out *bytes.Buffer, depth int) {
	indent := func(level int) { out.WriteString(strings.Repeat("  ", level)) }

	switch v.kind {
	case jsonNull:
		out.WriteString("null")
	case jsonFalse:
		out.WriteString("false")
	case jsonTrue:
		out.WriteString("true")
	case jsonNumber:
		out.WriteString(v.text)
	case jsonString:
		out.WriteString(jqString(v.text))
	case jsonArray:
		if len(v.items) == 0 {
			out.WriteString("[]")

			return
		}

		out.WriteString("[\n")

		for at, item := range v.items {
			if at > 0 {
				out.WriteString(",\n")
			}

			indent(depth + 1)
			item.pretty(out, depth+1)
		}

		out.WriteString("\n")
		indent(depth)
		out.WriteString("]")
	case jsonObject:
		if len(v.keys) == 0 {
			out.WriteString("{}")

			return
		}

		out.WriteString("{\n")

		for at, key := range v.keys {
			if at > 0 {
				out.WriteString(",\n")
			}

			indent(depth + 1)
			out.WriteString(jqString(key) + ": ")
			v.values[key].pretty(out, depth+1)
		}

		out.WriteString("\n")
		indent(depth)
		out.WriteString("}")
	}
}

// jqString quotes a string as jq does: only the quote, the backslash and the control characters
// are escaped, DEL included, and everything else — HTML characters, U+2028 — is written as it is.
// encoding/json escapes more than that, and a fingerprint is a hash of the exact bytes.
func jqString(value string) string {
	var b strings.Builder

	b.WriteByte('"')

	for _, r := range value {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\b':
			b.WriteString(`\b`)
		case r == '\f':
			b.WriteString(`\f`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04x`, r)
		default:
			b.WriteRune(r)
		}
	}

	b.WriteByte('"')

	return b.String()
}
